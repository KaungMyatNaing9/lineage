from __future__ import annotations

from pathlib import Path

from lineage.discover import is_test_path, leading_license_span, load_corpus


def test_license_header_span_keeps_real_line_numbers(tmp_path: Path) -> None:
    text = (
        "# Copyright 2026 Example Author\n"
        "# SPDX-License-Identifier: MIT\n"
        "\n"
        "def run():\n"
        "    return 1\n"
    )
    assert leading_license_span(text, "python") == 3
    path = tmp_path / "mod.py"
    path.write_text(text, encoding="utf-8")
    corpus = load_corpus(path)
    assert corpus.files[0].license_skip_lines == 3
    assert "def run" in corpus.files[0].text.splitlines()[3]


def test_vendored_generated_and_minified_files_are_skipped(tmp_path: Path) -> None:
    root = tmp_path / "proj"
    (root / "src").mkdir(parents=True)
    (root / "vendor").mkdir()
    (root / "src" / "app.py").write_text("def run():\n    return 1\n", encoding="utf-8")
    (root / "vendor" / "lib.py").write_text("def vendored():\n    return 2\n", encoding="utf-8")
    (root / "src" / "gen.py").write_text(
        "# Generated by the widget tool. Do not edit.\n" + "x = 1\n" * 5,
        encoding="utf-8",
    )
    (root / "src" / "bundle.js").write_text("function a(){return 1}" + ("x" * 500) + "\n" * 2, encoding="utf-8")
    corpus = load_corpus(root)
    assert [item.rel_path for item in corpus.files] == ["src/app.py"]
    reasons = {reason for _path, reason in corpus.skipped}
    assert "vendored path" in reasons
    assert "generated header" in reasons
    assert "minified" in reasons


def test_include_vendored_flag(tmp_path: Path) -> None:
    root = tmp_path / "proj"
    (root / "vendor").mkdir(parents=True)
    (root / "vendor" / "lib.py").write_text("def vendored():\n    return 2\n", encoding="utf-8")
    corpus = load_corpus(root, include_vendored=True)
    assert [item.rel_path for item in corpus.files] == ["vendor/lib.py"]


def test_test_path_detection() -> None:
    assert is_test_path("tests/test_app.py")
    assert is_test_path("src/app_test.go")
    assert is_test_path("pkg/widget.spec.ts")
    assert not is_test_path("src/app.py")
